# NEW — shared PDF layout helpers for both report types (fpdf2, pure
# Python, no external binary/browser-rendering dependency).

from datetime import datetime, timezone
from zoneinfo import ZoneInfo

from fpdf import FPDF
from fpdf.enums import XPos, YPos

# fpdf2's core fonts (Helvetica etc.) encode to Latin-1, which can't
# represent the em-dashes/curly quotes this codebase's own prose style
# uses constantly, and that LLM output (which tends to mimic surrounding
# style, and is never guaranteed plain-ASCII regardless) may well contain
# too. Swaps the specific characters actually likely in practice for
# plain ASCII equivalents, then falls back to lossy Latin-1 replacement
# for anything else exotic rather than let an unexpected character crash
# report generation outright -- confirmed necessary directly: an
# unsanitized em-dash raises inside fpdf2's text-layout code, not a
# hypothetical concern.
_UNICODE_REPLACEMENTS = {
    "—": "-", "–": "-",  # em dash, en dash
    "‘": "'", "’": "'",  # curly single quotes
    "“": '"', "”": '"',  # curly double quotes
    "…": "...",  # ellipsis
    "•": "-",  # bullet
}


def sanitize(text) -> str:
    if text is None:
        return ""
    text = str(text)
    for uni, ascii_eq in _UNICODE_REPLACEMENTS.items():
        text = text.replace(uni, ascii_eq)
    return text.encode("latin-1", errors="replace").decode("latin-1")


def format_mauritius(dt: datetime | None) -> str:
    """Same Indian/Mauritius (UTC+4, no DST) conversion dashboard/app.js's
    timestamp() applies to every timestamp shown on the dashboard -- a
    report generated from that same data should read consistently with
    it, not silently switch to UTC or the server's own local time."""
    if dt is None:
        return "unknown"
    if dt.tzinfo is None:
        dt = dt.replace(tzinfo=timezone.utc)
    mauritius = dt.astimezone(ZoneInfo("Indian/Mauritius"))
    return mauritius.strftime("%Y-%m-%d %H:%M:%S") + " MUT"


class ReportPDF(FPDF):
    """Shared page setup so a per-alert and a per-employee report look
    like they came from the same system rather than two unrelated
    documents -- consistent margins/fonts and a generated-at footer."""

    def footer(self):
        self.set_y(-15)
        self.set_font("Helvetica", "I", 8)
        self.set_text_color(120, 120, 120)
        self.cell(0, 10, sanitize(f"Generated by litds -- {format_mauritius(datetime.now(timezone.utc))}"), align="C")
        self.set_text_color(0, 0, 0)


def new_report(title: str, subtitle: str = "") -> ReportPDF:
    pdf = ReportPDF()
    pdf.set_auto_page_break(auto=True, margin=20)
    pdf.add_page()
    pdf.set_font("Helvetica", "B", 18)
    pdf.multi_cell(0, 10, sanitize(title), new_x=XPos.LMARGIN, new_y=YPos.NEXT)
    if subtitle:
        pdf.set_font("Helvetica", "", 11)
        pdf.set_text_color(90, 90, 90)
        pdf.multi_cell(0, 7, sanitize(subtitle), new_x=XPos.LMARGIN, new_y=YPos.NEXT)
        pdf.set_text_color(0, 0, 0)
    pdf.ln(4)
    return pdf


def section_title(pdf: ReportPDF, text: str) -> None:
    pdf.ln(3)
    pdf.set_font("Helvetica", "B", 13)
    pdf.multi_cell(0, 8, sanitize(text), new_x=XPos.LMARGIN, new_y=YPos.NEXT)
    pdf.set_draw_color(200, 200, 200)
    pdf.line(pdf.l_margin, pdf.y, pdf.w - pdf.r_margin, pdf.y)
    pdf.ln(3)


def paragraph(pdf: ReportPDF, text: str, *, size: int = 11, italic: bool = False) -> None:
    pdf.set_font("Helvetica", "I" if italic else "", size)
    pdf.multi_cell(0, 6.5, sanitize(text), new_x=XPos.LMARGIN, new_y=YPos.NEXT)
    pdf.ln(1)


def bold_line(pdf: ReportPDF, text: str, *, size: float = 10.5) -> None:
    """A short bold standalone line (e.g. "Supporting log evidence:", an
    alert's own title heading) -- multi_cell rather than a raw cell() so
    genuinely dynamic/variable-length text (an alert title, sourced from
    Alert.title) wraps onto a second line instead of silently overflowing
    past the page edge and getting visually cut off -- confirmed live
    this actually happens with a real long title before this helper
    existed, not just a theoretical concern."""
    pdf.set_font("Helvetica", "B", size)
    pdf.multi_cell(0, size * 0.62, sanitize(text), new_x=XPos.LMARGIN, new_y=YPos.NEXT)


def label_value(pdf: ReportPDF, label: str, value: str) -> None:
    pdf.set_font("Helvetica", "", 10.5)
    pdf.multi_cell(0, 6.5, sanitize(f"**{label}:** {value}"), new_x=XPos.LMARGIN, new_y=YPos.NEXT, markdown=True)


def bullet(pdf: ReportPDF, text: str, *, indent: str = "") -> None:
    pdf.set_font("Helvetica", "", 10)
    pdf.multi_cell(0, 6, sanitize(f"{indent}- {text}"), new_x=XPos.LMARGIN, new_y=YPos.NEXT)


def empty_note(pdf: ReportPDF, text: str) -> None:
    pdf.set_font("Helvetica", "I", 10.5)
    pdf.set_text_color(110, 110, 110)
    pdf.multi_cell(0, 6.5, sanitize(text), new_x=XPos.LMARGIN, new_y=YPos.NEXT)
    pdf.set_text_color(0, 0, 0)


def to_bytes(pdf: ReportPDF) -> bytes:
    return bytes(pdf.output())
